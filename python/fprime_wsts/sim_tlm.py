"""Telemetry of the simulation itself, written for a deployment: the traffic of each bus endpoint,
the timing of the run, and each link to another element of a system.

The channels belong to a component written for the deployment, `WstsAdapted.SimTelemetry`
(instance `wstsTlm`): its endpoints and links are the deployment's, which a toolkit component
cannot have in its dictionary. It is passive: `Wsts.SimControl` publishes it with its own
telemetry, once a second (a simulated second in stepped time), through
`Wsts::Control::addTelemetrySource`.

Groups (`telemetry` in the manifest turns each off):

* bus: per endpoint, `<endpoint>_FromFlight`, `_ToFlight`, `_BytesOut`, `_BytesIn`, `_Errors`,
  `_Unanswered` (the counters of Bus::traffic()), and `_RateOut`, `_RateIn`: bytes per simulated
  second since the last publication.
* timing: `SimSeconds`, `BusyTicks`, `LateTicks`, and `Speed` (simulated seconds per second of
  the host's clock). Speed depends on the host, so it is written in real time only: in stepped
  time a system's telemetry crosses its links, and two runs must send the same bytes.
* links: per link, `<link>_Sent`, `<link>_Received` (messages) and `<link>_Up`.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import List

from .registers import ADAPTED_MODULE

COMPONENT_BASE = "SimTelemetry"
COMPONENT = f"{ADAPTED_MODULE}.{COMPONENT_BASE}"
INSTANCE = "wstsTlm"
DIRECTORY = f"{ADAPTED_MODULE}/{COMPONENT_BASE}"
HEADER = f"{DIRECTORY}/{COMPONENT_BASE}.hpp"
#: Offset of the instance's base ID in the block of Wsts.SimControl, whose own IDs are below 0x100
BASE_OFFSET = 0x800

#: Per endpoint: (suffix, type, EndpointTraffic member or rate of one, description)
BUS = [
    ("FromFlight", "U64", "toDevice", "Transactions flight software made: sends, reads, writes, transfers, pin writes"),
    ("ToFlight", "U64", "toFlight", "What reached flight software unasked: received bytes, input levels, interrupts"),
    ("BytesOut", "U64", "bytesToDevice", "Bytes sent, written or shifted out"),
    ("BytesIn", "U64", "bytesToFlight", "Bytes received or read back"),
    ("Errors", "U64", "errors", "Transactions that returned an error status"),
    ("Unanswered", "U64", "unanswered", "Transactions nothing answered: no device, none at the address or offset"),
]
RATES = [
    ("RateOut", "bytesToDevice", "Bytes sent, written or shifted out per simulated second"),
    ("RateIn", "bytesToFlight", "Bytes received or read back per simulated second"),
]
TIMING = [
    ("SimSeconds", "F64", "Simulated time since start-up, in seconds"),
    ("BusyTicks", "U64", "Ticks taken while work of an earlier one was outstanding"),
    ("LateTicks", "U64", "Real time: ticks taken after the next was already due (the host fell behind)"),
    ("Speed", "F32", "Real time: simulated seconds per second of the host's clock since the last publication"),
]
LINKS = [
    ("Sent", "U64", "Messages sent to the other element"),
    ("Received", "U64", "Messages received from the other element"),
    ("Up", "bool", "The other element is connected"),
]


@dataclass
class Plan:
    endpoints: List[str]
    links: List[str]
    timing: bool

    def __bool__(self) -> bool:
        return bool(self.endpoints or self.links or self.timing)

    def channel_names(self) -> List[str]:
        names = [f"{_identifier(e)}_{suffix}" for e in self.endpoints for suffix, *_ in BUS]
        names += [f"{_identifier(e)}_{suffix}" for e in self.endpoints for suffix, *_ in RATES]
        names += [name for name, *_ in TIMING] if self.timing else []
        names += [f"{_identifier(link)}_{suffix}" for link in self.links for suffix, *_ in LINKS]
        return names


def _identifier(text: str) -> str:
    name = re.sub(r"\W", "_", text)
    return name if re.match(r"[A-Za-z_]", name) else f"x_{name}"


def _cpp_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def check(plan: Plan) -> str:
    """Why these channels cannot be written, or an empty string. An endpoint and a link may share
    a name: their channels have different suffixes."""
    clashes = []
    for group in (plan.endpoints, plan.links):
        by_name: dict = {}
        for name in group:
            by_name.setdefault(_identifier(name), []).append(name)
        clashes += [" and ".join(f"'{n}'" for n in names) for names in by_name.values() if len(names) > 1]
    if clashes:
        return (f"{'; '.join(clashes)} give simulation channels the same names: names that differ only in characters "
                "other than letters, digits and _ are not told apart. Rename one, or turn the group off with "
                "'telemetry' in the manifest")
    return ""


def render_fpp(plan: Plan) -> str:
    lines = [
        "# Generated by fprime-wsts. Do not edit: regenerate with `fprime-wsts generate`.",
        "",
        f"module {ADAPTED_MODULE} {{",
        "",
        "  @ The simulation's own telemetry for this deployment: the traffic of each bus endpoint,",
        "  @ the timing of the run and each link to another element. Published with the telemetry",
        "  @ of the WSTS control component.",
        f"  passive component {COMPONENT_BASE} {{",
        "",
        "    telemetry port tlmOut",
        "",
        "    time get port timeCaller",
        "",
    ]
    for endpoint in plan.endpoints:
        for suffix, kind, _, description in BUS:
            lines += [f"    @ {endpoint}: {description}", f"    telemetry {_identifier(endpoint)}_{suffix}: {kind}", ""]
        for suffix, _, description in RATES:
            lines += [f"    @ {endpoint}: {description}", f"    telemetry {_identifier(endpoint)}_{suffix}: F32", ""]
    if plan.timing:
        for name, kind, description in TIMING:
            lines += [f"    @ {description}", f"    telemetry {name}: {kind}", ""]
    for link in plan.links:
        for suffix, kind, description in LINKS:
            lines += [f"    @ Link {link}: {description}", f"    telemetry {_identifier(link)}_{suffix}: {kind}", ""]
    lines += ["  }", "", "}"]
    return "\n".join(lines) + "\n"


def render_header(plan: Plan) -> str:
    guard = f"WSTS_ADAPTED_{COMPONENT_BASE.upper()}_HPP"
    body: List[str] = []
    if plan.endpoints:
        body += ["        const std::map<std::string, Wsts::EndpointTraffic> traffic = Wsts::Bus::get().traffic();"]
    for index, endpoint in enumerate(plan.endpoints):
        name = _identifier(endpoint)
        body += [
            "        {",
            f"            const auto found = traffic.find({_cpp_string(endpoint)});",
            "            const Wsts::EndpointTraffic t = (found == traffic.end()) ? Wsts::EndpointTraffic() : found->second;",
            *[f"            this->tlmWrite_{name}_{suffix}(t.{member});" for suffix, _, member, _ in BUS],
            "            if (seconds > 0.0) {",
            *[f"                this->tlmWrite_{name}_{suffix}(rate(t.{member}, m_last[{index}][{i}], seconds));"
              for i, (suffix, member, _) in enumerate(RATES)],
            "            }",
            *[f"            m_last[{index}][{i}] = t.{member};" for i, (_, member, _) in enumerate(RATES)],
            "        }",
        ]
    if plan.timing:
        body += [
            "        const Wsts::SimStatus status = Wsts::Control::get().status();",
            "        this->tlmWrite_SimSeconds(status.simSeconds);",
            "        this->tlmWrite_BusyTicks(status.busyTicks);",
            "        this->tlmWrite_LateTicks(status.lateTicks);",
            "        // The host's clock: real time only (in stepped time two runs must send the same bytes)",
            "        const auto wall = std::chrono::steady_clock::now();",
            "        if (!status.stepped && m_published && seconds > 0.0) {",
            "            const double host = std::chrono::duration<double>(wall - m_lastWall).count();",
            "            if (host > 0.0) {",
            "                this->tlmWrite_Speed(static_cast<F32>(seconds / host));",
            "            }",
            "        }",
            "        m_lastWall = wall;",
        ]
    for link in plan.links:
        name = _identifier(link)
        body += [
            "        {",
            f"            Wsts::LinkEnd* link = Wsts::LinkRegistry::find({_cpp_string(link)});",
            "            if (link != nullptr) {",
            f"                this->tlmWrite_{name}_Sent(link->sent());",
            f"                this->tlmWrite_{name}_Received(link->received());",
            f"                this->tlmWrite_{name}_Up(link->isUp());",
            "            }",
            "        }",
        ]
    lines = [
        "// Generated by fprime-wsts. Do not edit: regenerate with `fprime-wsts generate`.",
        "//",
        "// The simulation's own telemetry for this deployment (python/fprime_wsts/sim_tlm.py).",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <array>",
        "#include <chrono>",
        "#include <cstdint>",
        "#include <map>",
        "#include <string>",
        "",
        "#include <Wsts/Core/Bus.hpp>",
        "#include <Wsts/Core/Control.hpp>",
        "#include <Wsts/Core/LinkRegistry.hpp>",
        f"#include <{DIRECTORY}/{COMPONENT_BASE}ComponentAc.hpp>",
        "",
        f"namespace {ADAPTED_MODULE} {{",
        "",
        f"class {COMPONENT_BASE} final : public {COMPONENT_BASE}ComponentBase {{",
        "  public:",
        f"    explicit {COMPONENT_BASE}(const char* compName) : {COMPONENT_BASE}ComponentBase(compName) {{}}",
        "",
        "    //! Write every channel (Wsts.SimControl, with its own telemetry)",
        "    void wstsPublish() {",
        "        // Simulated seconds since the last publication, for the rates",
        "        const std::uint64_t now = Wsts::Control::get().elapsedNs();",
        "        const double seconds = (m_published && now > m_lastNs) ? static_cast<double>(now - m_lastNs) * 1e-9 : 0.0;",
        *body,
        "        m_lastNs = now;",
        "        m_published = true;",
        "    }",
        "",
        "  private:",
        "    static F32 rate(std::uint64_t count, std::uint64_t last, double seconds) {",
        "        return (count < last) ? 0.0F : static_cast<F32>(static_cast<double>(count - last) / seconds);",
        "    }",
        "",
        "    bool m_published = false;",
        "    std::uint64_t m_lastNs = 0;",
        "    std::chrono::steady_clock::time_point m_lastWall;",
        f"    std::array<std::array<std::uint64_t, {len(RATES)}>, {max(len(plan.endpoints), 1)}> m_last{{}};",
        "};",
        "",
        f"}}  // namespace {ADAPTED_MODULE}",
        "",
        "#endif",
    ]
    return "\n".join(lines) + "\n"


def render_cmake() -> str:
    return "\n".join([
        "# Generated by fprime-wsts. Do not edit: regenerate with `fprime-wsts generate`.",
        "register_fprime_library(",
        "    AUTOCODER_INPUTS",
        f'        "${{CMAKE_CURRENT_LIST_DIR}}/{COMPONENT_BASE}.fpp"',
        "    HEADERS",
        f'        "${{CMAKE_CURRENT_LIST_DIR}}/{COMPONENT_BASE}.hpp"',
        "    DEPENDS",
        "        Wsts_Core",
        ")",
        "",
    ])


def write(plan: Plan, overlay: Path) -> Path:
    """Write the module into the overlay. Returns its FPP file."""
    directory = overlay / DIRECTORY
    directory.mkdir(parents=True, exist_ok=True)
    model = directory / f"{COMPONENT_BASE}.fpp"
    model.write_text(render_fpp(plan))
    (directory / f"{COMPONENT_BASE}.hpp").write_text(render_header(plan))
    (directory / "CMakeLists.txt").write_text(render_cmake())
    return model


def setup_lines(instance: str) -> List[str]:
    """C++ of the generated set-up that has Wsts.SimControl publish the component"""
    return ["", "    // The simulation's own telemetry: bus traffic, timing, links",
            f"    Wsts::Control::get().addTelemetrySource([] {{ {instance}.wstsPublish(); }});"]
